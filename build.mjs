// TTB build — assembles a loadable package per browser from one source tree.
//
//   node build.mjs            → dist/chrome, dist/edge, dist/firefox, dist/safari
//   node build.mjs firefox    → just one target
//
// Each package is the same shared code with a target-specific manifest and a
// data/target.js marker. Nothing is transpiled or bundled — TTB has no build
// step beyond picking the right manifest and writing the README for the target.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(fileURLToPath(new URL('.', import.meta.url)));
const DIST = path.join(ROOT, 'dist');
// Live tool count, derived from the authoritative catalog so generated docs never go stale.
const CATALOG_COUNT = (fs.readFileSync(path.join(ROOT, 'data', 'tools.js'), 'utf8').match(/"id":/g) || []).length;

// Files that belong to the repository, not to a shipped extension package.
const EXCLUDE = new Set(['dist', '.git', '.github', 'node_modules', 'docs', 'browsers',
  'test.mjs', 'screenshots.mjs', 'build.mjs', 'package.json', 'package-lock.json',
  '.gitignore', '.gitattributes', 'BROWSER_SUPPORT.md', 'CONTRIBUTING.md', 'AUDIT.md']);

// Feature parity across targets. true = works, false = API absent, 'partial' /
// 'fallback' / 'verify' = see the note in the generated docs.
const FEATURES = [
  ['Tool catalog, search and category browser', true, true, true, true],
  ['Per-tool inputs, HTML preview, image output', true, true, true, true],
  ['Text, calculator, developer, data and design tools', true, true, true, true],
  ['Page tools (extract, read, restyle, restore)', true, true, true, true],
  ['Tab tools (search, pin, mute, reload, close duplicates)', true, true, true, true],
  ['Real crypto (TOTP/HOTP, AES-GCM, PBKDF2, hashing)', true, true, true, true],
  ['Side panel / sidebar', true, true, 'sidebar_action', false],
  ['Browsing history tools', true, true, true, false],
  ['Bookmark tools', true, true, true, false],
  ['Cookie tools', true, true, true, 'partial'],
  ['Downloads manager', true, true, true, false],
  ['Cache / cookie / history clearing', true, true, true, false],
  ['Extension manager', true, true, true, false],
  ['Installed fonts viewer', true, true, true, false],
  ['Tab capture / screenshots', true, true, true, 'verify'],
  ['File downloads from tools', true, true, true, 'fallback'],
  ['QR / barcode scanning', true, true, false, false],
  ['Screen colour picker', true, true, false, false],
  ['Text-to-speech / speech recognition', true, true, 'partial', 'partial'],
  ['Screen / audio / webcam recording', true, true, true, 'verify'],
];
const TARGETS = ['chrome', 'edge', 'firefox', 'safari'];
const MARK = (v) => v === true ? '✅ yes' : v === false ? '— no' : `◐ ${v}`;

function buildManifest(target) {
  const base = JSON.parse(fs.readFileSync(path.join(ROOT, 'manifest.json'), 'utf8'));
  const frag = JSON.parse(fs.readFileSync(path.join(ROOT, 'browsers', `${target}.json`), 'utf8'));
  for (const k of frag.exclude || []) delete base[k];
  if (frag.permissions_remove?.length) base.permissions = (base.permissions || []).filter((p) => !frag.permissions_remove.includes(p));
  Object.assign(base, frag.set || {});
  if (frag.name) base.name = frag.name;
  // keep a stable, target-specific ordering for reviewability
  const ordered = {};
  for (const k of ['manifest_version', 'name', 'version', 'description', 'minimum_chrome_version', 'browser_specific_settings', 'permissions', 'action', 'sidebar_action', 'side_panel', 'background', 'commands', 'icons']) {
    if (k in base) ordered[k] = base[k];
  }
  for (const k of Object.keys(base)) if (!(k in ordered)) ordered[k] = base[k];
  return ordered;
}

function buildReadme(target, frag, manifest) {
  const idx = TARGETS.indexOf(target);
  const rows = FEATURES.map((f) => `| ${f[0]} | ${MARK(f[1 + idx])} |`).join('\n');
  const excluded = FEATURES.filter((f) => f[1 + idx] === false).map((f) => `- **${f[0]}** — the browser does not expose this API. The tool is present in the catalog and reports the limitation instead of failing silently.`).join('\n') || '- None — full feature parity with the Chromium build.';
  const partial = FEATURES.filter((f) => typeof f[1 + idx] === 'string').map((f) => `- **${f[0]}** — ${f[1 + idx]}.`).join('\n') || '- None.';
  return `# TTB — Tiny Toolbox · ${target} build

${frag.notes}

Version ${manifest.version}. Generated by \`node build.mjs ${target}\` — do not edit by hand.

## Loading this build

${target === 'firefox' ? `1. Open \`about:debugging#/runtime/this-firefox\`.
2. Choose **Load Temporary Add-on…** and pick \`manifest.json\` in this folder.
3. For a permanent install, package the folder as a ZIP and sign it on addons.mozilla.org.` : target === 'safari' ? `Safari cannot load an unpacked folder. Convert this folder with Xcode:

\`\`\`
xcrun safari-web-extension-converter /path/to/dist/safari \\
  --project-location ./TTB-safari --app-name "TTB Tiny Toolbox" --bundle-identifier com.drsamonline.ttb
\`\`\`

Then open the generated Xcode project, set your signing team, and run it. Enable the extension in **Safari → Settings → Extensions**.` : `1. Open \`chrome://extensions\` (or \`edge://extensions\`).
2. Enable **Developer mode**.
3. Choose **Load unpacked** and select this folder.
4. Pin TTB and open the popup.`}

## Feature parity

| Capability | ${target} |
|---|---|
${rows}

### Not available on this target
${excluded}

### Reduced or needs checking
${partial}

Everything else — the ${CATALOG_COUNT}-tool catalog, the popup UI, per-tool inputs, page tools, crypto, and all pure-computation tools — is identical to the Chromium build.
`;
}

function copyTree(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (EXCLUDE.has(entry.name)) continue;
    const s = path.join(src, entry.name), d = path.join(dest, entry.name);
    if (entry.isDirectory()) copyTree(s, d);
    else fs.copyFileSync(s, d);
  }
}

const requested = process.argv.slice(2).filter((a) => !a.startsWith('-'));
const targets = requested.length ? requested : TARGETS;
fs.rmSync(DIST, { recursive: true, force: true });

const summary = [];
for (const target of targets) {
  if (!TARGETS.includes(target)) { console.error('unknown target:', target); process.exit(1); }
  const frag = JSON.parse(fs.readFileSync(path.join(ROOT, 'browsers', `${target}.json`), 'utf8'));
  const out = path.join(DIST, target);
  copyTree(ROOT, out);
  const manifest = buildManifest(target);
  fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  fs.writeFileSync(path.join(out, 'data', 'target.js'),
    `// Build target marker — written by build.mjs.\nexport const TARGET = '${target}';\n`);
  fs.writeFileSync(path.join(out, 'README-BUILD.md'), buildReadme(target, frag, manifest));
  // verify the package is structurally loadable
  const bg = manifest.background?.service_worker || (manifest.background?.scripts || [])[0];
  for (const f of ['manifest.json', 'popup.html', 'sidebar.html', 'data/tools.js', 'data/target.js', 'ui/app.js', bg]) {
    if (!f || !fs.existsSync(path.join(out, f))) throw new Error(`${target}: package is missing ${f}`);
  }
  const cat = fs.readFileSync(path.join(out, 'data/tools.js'), 'utf8');
  if (!cat.includes('globalThis.TTB_CATALOG')) throw new Error(`${target}: catalog missing`);
  if (manifest.background?.service_worker && manifest.background?.scripts) throw new Error(`${target}: both service_worker and scripts present (Chrome rejects this)`);
  summary.push({ target, manifest: manifest.manifest_version, background: Object.keys(manifest.background || {}).join('+'), permissions: (manifest.permissions || []).length });
  console.log(`built dist/${target}  (background: ${Object.keys(manifest.background || {}).join('+')}, ${(manifest.permissions || []).length} permissions)`);
}

// repository-level support matrix
const header = `# Browser support

TTB ships from one source tree and is assembled per browser with \`npm run build\`.
Every build carries the full ${CATALOG_COUNT}-tool catalog; tools that need an API a browser
does not provide are disabled and say so plainly rather than failing silently.

| Capability | Chrome | Edge | Firefox | Safari |
|---|---|---|---|---|
${FEATURES.map((f) => `| ${f[0]} | ${MARK(f[1])} | ${MARK(f[2])} | ${MARK(f[3])} | ${MARK(f[4])} |`).join('\n')}

**Legend** — ✅ works · — the API is absent on that browser · ◐ reduced, see below.

## What each build changes

| | Chrome / Edge | Firefox | Safari |
|---|---|---|---|
| Background | MV3 service worker | MV3 event page (\`background.scripts\`) | MV3 service worker |
| Side panel | \`side_panel\` | \`sidebar_action\` | none |
| Manifest notes | — | \`browser_specific_settings.gecko.id\` | no privileged browser APIs |

## Known gaps, in detail

- **Firefox** has no \`background.service_worker\`, so the build uses an event page. It has no side panel; the sidebar is opened through \`sidebar_action\`. \`BarcodeDetector\` and \`EyeDropper\` are not implemented, so QR/barcode scanning and the screen colour picker report that.
- **Safari** exposes no history, bookmarks, downloads, management, browsingData or fontSettings APIs at all, so those tools are disabled. \`storage.sync\` does not sync (it behaves like \`local\`), so TTB uses \`local\` everywhere. Safari also needs an Xcode conversion step — see the build README. Cookie access and tab capture should be verified on your Safari version.
- **Chromium browsers** (Chrome, Edge, Brave, Opera, Vivaldi, Arc) run the same package with no changes; the Edge build is produced only so the artifact is labelled.
- **Downloads** fall back to an \`<a download>\` click when the downloads API is unavailable, so image and file tools still save their output on Safari.
- **Recording** tools need a permission prompt on every browser and keep the popup open while they run.
`;
fs.writeFileSync(path.join(ROOT, 'BROWSER_SUPPORT.md'), header);
console.log('\n' + JSON.stringify(summary, null, 2));
console.log('wrote BROWSER_SUPPORT.md');
